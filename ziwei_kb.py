_KB_DIR = os.path.dirname(os.path.abspath(__file__))
_concepts_cache: Any = None
_geju_cache: Any = None
_qa_cache: Any = None


def _load_concepts() -> list:
    global _concepts_cache
    if _concepts_cache is None:
        try:
            with open(os.path.join(_KB_DIR, "ziwei_concepts.json"), encoding="utf-8") as f:
                _concepts_cache = json.load(f)
        except Exception:
            _concepts_cache = []
    return _concepts_cache or []


def _load_geju() -> list:
    global _geju_cache
    if _geju_cache is None:
        try:
            with open(os.path.join(_KB_DIR, "ziwei_geju.json"), encoding="utf-8") as f:
                _geju_cache = json.load(f)
        except Exception:
            _geju_cache = []
    return _geju_cache or []


def _load_qa() -> list:
    global _qa_cache
    if _qa_cache is None:
        try:
            with open(os.path.join(_KB_DIR, "ziwei_qa.json"), encoding="utf-8") as f:
                _qa_cache = json.load(f)
        except Exception:
            _qa_cache = []
    return _qa_cache or []


def lookup_concept(term: str) -> str:
    """查概念的「古籍应证」片段（返回单条格式化文本，未命中返回空串）。"""
    for c in _load_concepts():
        if c.get("term") == term or term in (c.get("aliases") or []):
            snips = c.get("snippets") or []
            parts = [f"《{s.get('title', '')}》：{s.get('text', '')}" for s in snips[:2]]
            return f"· {c.get('term')}（{c.get('category', '')}）古籍应证：" + "；".join(parts)
    return ""


def lookup_geju(name: str) -> str:
    """查格局的古籍应证（返回单条格式化文本，未命中返回空串）。"""
    for g in _load_geju():
        if g.get("normalized") == name or g.get("name") == name:
            meaning = g.get("meaning", "")
            snips = g.get("sources") or []
            parts = [f"《{s.get('title', '')}》：{s.get('text', '')}" for s in snips[:2]]
            return f"· {g.get('name')}（古籍格局）：{meaning}" + ("；".join(parts) if parts else "")
    return ""


def lookup_qa(concept: str) -> str:
    """查概念问答（返回单条格式化文本，未命中返回空串）。"""
    for q in _load_qa():
        if q.get("concept") == concept:
            return f"· 问：{q.get('question', '')} 答：{str(q.get('answer', ''))[:200]}"
    return ""


