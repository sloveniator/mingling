def _hexagram(name: str):
    """按卦名查六十四卦卦象（兼容全称/简称，返回 dict 或 None）。"""
    if not name:
        return None
    if name in HEXAGRAM_KB:
        return HEXAGRAM_KB[name]
    # 简称匹配（如「无妄」「谦」「泰」）
    for full, entry in HEXAGRAM_KB.items():
        short = full.replace("为", "").replace("水", "").replace("火", "").replace("雷", "").replace("风", "").replace("山", "").replace("泽", "").replace("天", "").replace("地", "")
        if name == short or name == full:
            return entry
    return None


def _format_hexagram(name: str) -> str:
    """格式化单卦卦象为可读文本（用于六爻/梅花断卦 grounding）。"""
    hx = _hexagram(name)
    if not hx:
        return ""
    return (
        f"· 【{name}】五行属{hx['wx']}。卦辞：{hx['ci']}"
        f" 象曰：{hx['xiang']} 判曰：{hx['pan']}"
    )


