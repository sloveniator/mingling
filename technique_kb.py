# 构建八字解读知识库 grounding（精准、相关、可引用）
# ------------------------------------------------------------
def build_bazi_knowledge_grounding(chart: Dict[str, Any]) -> str:
    """按命盘字段注入八字技法知识库条目，作为 LLM 专业解读的 grounding。

    chart 为 mingbu 后端 /api/bazi 返回的 BaziChart（{chart: {...}} 内的 chart）。
    全程容错：字段缺失时优雅降级，绝不抛错。
    """
    try:
        if not isinstance(chart, dict):
            return ""
        lines: List[str] = []
        dm = chart.get("dayMaster") or {}
        element = dm.get("element", "")
        yin_yang = str(dm.get("yinYang", ""))
        gan = dm.get("gan", "?")

        # 无日主信息视为非有效命盘，不注入技法 grounding
        if not gan or gan == "?" or not element:
            return ""

        lines.append("【八字知识库 · 日主本性】")
        dm_kb = DAYMASTER_KB.get(element, {})
        key = "yang" if yin_yang == "阳" else "yin"
        lines.append(f"· 日主{gan}（{element}·{yin_yang}）：{dm_kb.get(key, '')}")

        lines.append("")
        lines.append("【八字知识库 · 五行生克】")
        lines.append(WUXING_KOUJUE)

        ss_set = _collect_shi_shen(chart)
        if ss_set:
            lines.append("")
            lines.append("【八字知识库 · 十神详解（命局所现）】")
            for ss in ss_set:
                k = SHI_SHEN_KB.get(ss)
                if k:
                    lines.append(f"· {ss}：{k['mean']} {k['like']} {k['classic']}")

        pattern = chart.get("pattern") or {}
        pname = pattern.get("name", "")
        lines.append("")
        lines.append("【八字知识库 · 格局详解】")
        pkb = PATTERN_KB.get(pname) or PATTERN_KB.get(pname.replace("（杂气）", ""))
        if pkb:
            lines.append(f"· {pname}（{pattern.get('type', '')}）：{pkb['mean']} {pkb['classic']}")
        else:
            lines.append(f"· {pname}：{pattern.get('detail', '')}")

        lines.append("")
        lines.append("【八字知识库 · 用神喜忌与调候】")
        ys = chart.get("yongShen") or {}
        if ys.get("summary"):
            lines.append(f"· {ys['summary']}")
        dir_ = ELEMENT_DIRECTION.get(element)
        if dir_:
            lines.append(f"· 日主五行{element}之宜：方位【{dir_['direction']}】、颜色【{dir_['color']}】。")
        organ = ELEMENT_ORGAN.get(element)
        if organ:
            lines.append(f"· 养生参考：日主属{element}，对应{organ}（仅为传统文化养生参考，具体请就医）。")

        lines.append("")
        lines.append("【八字知识库 · 古籍原文印证】")
        for q in CLASSIC_QUOTES[:6]:
            lines.append(f"· {q['text']}")

        lines.append("")
        lines.append("【八字知识库 · 衰旺派方法论（日主旺衰法）】")
        lines.append(f"· 三得法（衰旺派）：{SHUAIWANG_KB['sande']}")
        lines.append(f"· 旺衰五级：{SHUAIWANG_KB['wuji']}")
        lines.append(f"· 调候为急（附调候派）：{SHUAIWANG_KB['tiao']}")
        lines.append(f"· 通关法：{SHUAIWANG_KB['tongguan']}")

        lines.append("")
        lines.append(_build_mangpai_grounding(chart))

        # 神煞
        lines.append("")
        lines.append("【八字知识库 · 神煞】")
        for name in ("天乙贵人", "文昌贵人", "羊刃", "桃花(咸池)", "驿马", "华盖", "将星", "劫煞", "天医", "禄神"):
            lines.append(f"· {name}：{SHENSHA_KB[name]}")

        # 地支刑冲合害
        lines.append("")
        lines.append("【八字知识库 · 地支刑冲合害】")
        for name in ("六合", "六冲", "三合", "三会", "三刑", "六害", "六破"):
            lines.append(f"· {name}：{ZHICHAO_KB[name]}")

        # 纳音（命局四柱纳音）
        nayin_hits = []
        for key in ("year", "month", "day", "hour"):
            p = chart.get(key) or {}
            if p.get("naYin"):
                nayin_hits.append(f"{p.get('gan', '')}{p.get('zhi', '')}{p.get('naYin')}")
        if nayin_hits:
            lines.append("")
            lines.append("【八字知识库 · 纳音（命局四柱）】")
            for hit in nayin_hits:
                nayin_name = hit[-3:]
                lines.append(f"· {hit}：{NAYIN_KB.get(nayin_name, '')}")

        return "\n".join(lines)
    except Exception:
        return ""


