_TRIGRAM_ORDER = ["乾", "兑", "离", "震", "巽", "坎", "艮", "坤"]


def _trigrams_of_name(name: str):
    """从卦名取上、下卦的八卦字符（兼容「泽火革」「天地否」「乾为天」等）。"""
    if not name:
        return None
    pure = re.match(r"^(.)(?:为|之)(.)$", name)
    if pure:
        t = _CHAR_TO_TRIGRAM.get(pure.group(1))
        if t:
            return (t, t)
    chars = [_CHAR_TO_TRIGRAM[c] for c in name if c in _CHAR_TO_TRIGRAM]
    if len(chars) >= 2:
        return (chars[0], chars[1])
    return None


