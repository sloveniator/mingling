# 工具：收集命局出现的十神
# ------------------------------------------------------------
def _collect_shi_shen(chart: Dict[str, Any]) -> List[str]:
    """收集命局出现的十神（四柱天干 + 藏干 + 首个非童限大运十神）。"""
    seen = set()
    out: List[str] = []
    for key in ("year", "month", "day", "hour"):
        p = chart.get(key) or {}
        for v in [p.get("shiShenGan"), *list(p.get("shiShenZhi") or [])]:
            if v and v not in seen:
                seen.add(v)
                out.append(v)
    for dy in chart.get("daYun") or []:
        if not dy.get("isTongXian") and dy.get("shiShen"):
            if dy["shiShen"] not in seen:
                seen.add(dy["shiShen"])
                out.append(dy["shiShen"])
            break
    return out


def _build_mangpai_grounding(chart: Dict[str, Any]) -> str:
    """盲派 grounding：宾主（财官落点）+ 体用做功方法论。"""
    lines = ["【八字知识库 · 盲派技法（宾主体用做功）】"]
    lines.append(f"· 总纲：{MANGPAI_KB['zonggang']}")

    pos_label = {"年": "宾·祖上外", "月": "宾·父母兄弟", "日": "主·我", "时": "主·门户子女"}
    pillars = [
        ("年", chart.get("year") or {}),
        ("月", chart.get("month") or {}),
        ("日", chart.get("day") or {}),
        ("时", chart.get("hour") or {}),
    ]
    cai_sha = []
    for label, p in pillars:
        if p.get("shiShenGan") in ("正财", "偏财", "正官", "七杀"):
            cai_sha.append(f"{label}干{p.get('gan', '')}({p.get('shiShenGan')})·{pos_label[label]}")
    loc = "；".join(cai_sha) if cai_sha else "天干无明现财官，须从地支藏干及大运流年寻体用做功"
    lines.append(f"· 宾主定位（财官落点）：{loc}")

    lines.append(f"· 体用：{MANGPAI_KB['tiyong']}")
    lines.append(f"· 做功五法：{MANGPAI_KB['zuogong']}")
    lines.append(f"· 功神废神：{MANGPAI_KB['gongshen']}")
